// design/tools/geometry.mjs (connect dock SVG shapes)  ->  app/lib/widgets/dock_paths.g.dart
//
// The mockup draws the dock tab in a viewBox 0 0 200 52 into a 200 x 52 px button (.power-tab),
// i.e. 1:1 — no scaling. Every shape is both the SVG path string (for reference / flutter_svg if
// ever wanted) and a Path built with explicit commands: the paths only use M L Q Z, so no runtime
// SVG parser is needed.
//
//   node app/tool/gen_dock.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { root, dartFormat } from './_util.mjs';

const { geometry } = await import(pathToFileURL(join(root, 'design/tools/geometry.mjs')).href);
const g = geometry();
const home = readFileSync(join(root, 'design/src/markup/10-home.html'), 'utf8');
const vb = /class="power-shape"\s+viewBox="0 0 (\d+) (\d+)"/.exec(home);
if (!vb) throw new Error('power-shape viewBox not found in 10-home.html');
const [W, H] = [+vb[1], +vb[2]];

const shapes = [
  ['frameFill', 'Dock frame filled down to the bottom edge (background of the dock + tab).'],
  ['frameLine', 'Dock top edge rising into the tab (stroke only, open path).'],
  ['powerHex', 'Centre of the power button: elongated hexagon.'],
  ['powerWedgeL', 'Left lower corner wedge of the power button.'],
  ['powerWedgeR', 'Right lower corner wedge of the power button.'],
];

// "M12,50 L5.5,41 Q…" -> Dart Path calls (absolute M L Q Z only)
function toDart(d) {
  const out = [];
  for (const m of d.matchAll(/([MLQZ])([^MLQZ]*)/g)) {
    const n = m[2].trim().split(/[\s,]+/).filter(Boolean).map(Number);
    switch (m[1]) {
      case 'M': out.push(`moveTo(${n[0]}, ${n[1]})`); break;
      case 'L': out.push(`lineTo(${n[0]}, ${n[1]})`); break;
      case 'Q': out.push(`quadraticBezierTo(${n[0]}, ${n[1]}, ${n[2]}, ${n[3]})`); break;
      case 'Z': out.push('close()'); break;
    }
  }
  const rest = d.replace(/[MLQZ0-9.,\s-]/g, '');
  if (rest) throw new Error('unsupported path command in: ' + d);
  return out.map(c => '..' + c).join('\n      ');
}

const num = v => String(v);
let s = `// GENERATED by app/tool/gen_dock.mjs from design/tools/geometry.mjs — do not edit.
// Re-run: node app/tool/gen_dock.mjs   (change the shapes in geometry.mjs, not here)

import 'dart:ui' show Path;

/// Connect dock shapes (Home). Coordinates live in a [width] x [height] box (logical px, drawn 1:1).
abstract final class DockGeometry {
  static const double width = ${W}.0;
  static const double height = ${H}.0;

  /// Vertical centre of the button (the power icon sits here).
  static const double iconCenterY = ${num(+g.iconCenterY)};
`;
for (const [name, doc] of shapes) {
  s += `
  /// ${doc}
  static const String ${name}Svg = '${g[name]}';
  static Path ${name}() => Path()
      ${toDart(g[name])};
`;
}
s += `}
`;

const outFile = join(root, 'app/lib/widgets/dock_paths.g.dart');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, s);
dartFormat(outFile);
console.log('gen_dock: 5 shapes -> app/lib/widgets/dock_paths.g.dart');
