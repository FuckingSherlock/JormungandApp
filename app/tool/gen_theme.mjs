// design/src/css/00-themes.css (+ THEMES in js/90-themes.js)  ->  app/lib/theme/app_colors.g.dart
//
// One const AppColors per theme (original / karing / github), a ThemeExtension<AppColors> with
// every colour variable of the mockup, and ThemeData builders. Widgets read colours only from
// the extension: `context.colors.card`, never `Color(0x…)` / `Colors.*` / `Theme.of().colorScheme`.
//
//   node app/tool/gen_theme.mjs        (re-runnable; `dart format` is run when dart is on PATH)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { root, dartFormat } from './_util.mjs';

const css = readFileSync(join(root, 'design/src/css/00-themes.css'), 'utf8');
const themesJs = readFileSync(join(root, 'design/src/js/90-themes.js'), 'utf8');
const outFile = join(root, 'app/lib/theme/app_colors.g.dart');

// ── parse the :root blocks (cascade: karing / github start from original) ──
const blocks = [];   // { ids: [..], vars: Map }
for (const m of css.matchAll(/(:root[^{]*)\{([^}]*)\}/g)) {
  const ids = [...m[1].matchAll(/data-theme="(\w+)"/g)].map(x => x[1]);
  if (!ids.length) continue;
  const vars = new Map();
  for (const v of m[2].matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) vars.set(v[1], v[2].trim());
  blocks.push({ ids, vars });
}
const original = blocks.find(b => b.ids.includes('original'));
if (!original) throw new Error('no original theme block in 00-themes.css');
const themes = new Map();   // id -> Map(var -> value), in CSS order
for (const b of blocks) for (const id of b.ids) {
  const vars = new Map(id === 'original' ? [] : original.vars);
  for (const [k, v] of b.vars) vars.set(k, v);
  themes.set(id, vars);
}

// ── THEMES = [{ id, name, sub, swatch }] from the mockup ──
const tm = /const THEMES = (\[[\s\S]*?\n\]);/.exec(themesJs);
const meta = tm ? new Function('return ' + tm[1])() : [];
const nameOf = id => (meta.find(t => t.id === id) || {}).name || id[0].toUpperCase() + id.slice(1);

// ── classify variables ──
const camel = s => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const isHex = v => /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.test(v);
const argb = v => {
  let h = v.slice(1);
  if (h.length === 3) h = [...h].map(c => c + c).join('');
  return '0xFF' + h.toUpperCase();
};
const colorNames = [], rgbNames = [], other = [];
for (const [k, v] of original.vars) {
  if (k.endsWith('-rgb')) rgbNames.push(k);
  else if (isHex(v)) colorNames.push(k);
  else other.push(k);
}
const fieldName = k => camel(k);   // bg, cardHi, accentDim, t1, qrDark …

// every `--x-rgb` must equal its `--x` (the Dart side drops them: rgba(var(--x-rgb), a) = x.tint(a))
const hexToRgb = v => { let h = v.slice(1); if (h.length === 3) h = [...h].map(c => c + c).join(''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)).join(','); };
for (const [id, vars] of themes) {
  for (const r of rgbNames) {
    const base = r.replace(/-rgb$/, '');
    if (!vars.has(base) || !isHex(vars.get(base))) throw new Error(`${id}: --${r} has no hex --${base}`);
    if (vars.get(r).replace(/\s+/g, '') !== hexToRgb(vars.get(base))) throw new Error(`${id}: --${r} (${vars.get(r)}) differs from --${base} (${vars.get(base)})`);
  }
}
const radii = k => { const v = /^([\d.]+)px$/.exec(k); if (!v) throw new Error('--r must be px: ' + k); return v[1].includes('.') ? v[1] : v[1] + '.0'; };
if (!other.includes('r')) throw new Error('--r missing');

// ── emit ──
const ids = [...themes.keys()];
const fields = [...colorNames.map(k => ({ name: fieldName(k), kind: 'color', key: k })), { name: 'radius', kind: 'double', key: 'r' }];
const val = (vars, f) => f.kind === 'color' ? `Color(${argb(vars.get(f.key))})` : radii(vars.get(f.key));
const type = f => (f.kind === 'color' ? 'Color' : 'double');

let d = `// GENERATED by app/tool/gen_theme.mjs from design/src/css/00-themes.css — do not edit.
// Re-run: node app/tool/gen_theme.mjs
//
// Every colour variable of the mockup, one const per theme. Widgets take colours only from here
// (\`context.colors.card\`). \`rgba(var(--accent-rgb), .15)\` in the CSS is \`colors.accent.tint(.15)\`.
// The CSS \`--*-rgb\` triples are not generated: they always equal the hex variable next to them.

import 'dart:ui' show lerpDouble;

import 'package:flutter/material.dart';

/// The themes of Settings → Appearance (same ids as the mockup's THEMES).
enum AppThemeId {
${ids.map(id => `  ${id}('${nameOf(id)}'),`).join('\n')}
  ;

  const AppThemeId(this.label);

  /// Proper name, not translated.
  final String label;

  AppColors get colors => AppColors.byId[this]!;

  static AppThemeId parse(String? id) => values.firstWhere((t) => t.name == id, orElse: () => AppThemeId.${ids[0]});
}

@immutable
class AppColors extends ThemeExtension<AppColors> {
  const AppColors({
${fields.map(f => `    required this.${f.name},`).join('\n')}
  });

${fields.map(f => `  ${f.kind === 'color' ? `/// --${f.key}` : `/// --${f.key}: corner radius of cards, rows and sheets`}\n  final ${type(f)} ${f.name};`).join('\n')}

${ids.map(id => `  static const ${id} = AppColors(\n${fields.map(f => `    ${f.name}: ${val(themes.get(id), f)},`).join('\n')}\n  );`).join('\n\n')}

  static const Map<AppThemeId, AppColors> byId = {
${ids.map(id => `    AppThemeId.${id}: ${id},`).join('\n')}
  };

  @override
  AppColors copyWith({
${fields.map(f => `    ${type(f)}? ${f.name},`).join('\n')}
  }) {
    return AppColors(
${fields.map(f => `      ${f.name}: ${f.name} ?? this.${f.name},`).join('\n')}
    );
  }

  @override
  AppColors lerp(ThemeExtension<AppColors>? other, double t) {
    if (other is! AppColors) return this;
    return AppColors(
${fields.map(f => f.kind === 'color' ? `      ${f.name}: Color.lerp(${f.name}, other.${f.name}, t)!,` : `      ${f.name}: lerpDouble(${f.name}, other.${f.name}, t)!,`).join('\n')}
    );
  }
}

extension AppColorsContext on BuildContext {
  AppColors get colors => Theme.of(this).extension<AppColors>()!;
}

extension AppTint on Color {
  /// \`rgba(var(--x-rgb), a)\` of the mockup.
  Color tint(double opacity) => withValues(alpha: opacity);
}

/// Bundled font with the Twemoji flags (Windows has no flag emoji); it only covers flag code points,
/// so it is a fallback, never the primary family (the mockup's \`--font\` lists it first for the same effect).
const String kFlagsFontFamily = 'Flags';

/// All themes are dark. Material 3; the colour scheme is only the bridge for stock widgets
/// (NavigationBar, Slider, Switch …) — app widgets use [AppColors].
ThemeData buildAppTheme(AppColors c) {
  final scheme = ColorScheme.dark(
    primary: c.accent,
    onPrimary: Colors.white,
    primaryContainer: c.accentDim,
    onPrimaryContainer: Colors.white,
    secondary: c.active,
    onSecondary: c.bg,
    secondaryContainer: c.activeDim,
    onSecondaryContainer: Colors.white,
    tertiary: c.purple,
    onTertiary: c.bg,
    error: c.danger,
    onError: c.bg,
    surface: c.surface,
    onSurface: c.t1,
    onSurfaceVariant: c.t2,
    outline: c.borderHi,
    outlineVariant: c.border,
    surfaceContainerLowest: c.bg,
    surfaceContainerLow: c.surface,
    surfaceContainer: c.card,
    surfaceContainerHigh: c.cardHi,
    surfaceContainerHighest: c.cardHi,
  );
  return ThemeData(
    useMaterial3: true,
    brightness: Brightness.dark,
    colorScheme: scheme,
    scaffoldBackgroundColor: c.bg,
    canvasColor: c.bg,
    fontFamilyFallback: const [kFlagsFontFamily],
    extensions: <ThemeExtension<dynamic>>[c],
    dividerTheme: DividerThemeData(color: c.border, space: 1, thickness: 1),
    navigationBarTheme: NavigationBarThemeData(
      backgroundColor: c.surface,
      indicatorColor: Colors.transparent,   // the mockup's .nav-btn: active = accent label, others dimmed
      height: 62,
      iconTheme: WidgetStateProperty.resolveWith(
        (states) => IconThemeData(size: 22, color: states.contains(WidgetState.selected) ? c.accent : c.t2.tint(.45)),
      ),
      labelTextStyle: WidgetStateProperty.resolveWith(
        (states) => TextStyle(
          fontSize: 12,
          fontWeight: FontWeight.w600,
          letterSpacing: .4,
          color: states.contains(WidgetState.selected) ? c.accent : c.t2.tint(.45),
        ),
      ),
    ),
  );
}

/// ThemeData per theme id, built once.
final Map<AppThemeId, ThemeData> appThemes = {
  for (final id in AppThemeId.values) id: buildAppTheme(id.colors),
};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, d);
dartFormat(outFile);
console.log(`gen_theme: ${ids.length} themes x ${fields.length} fields -> app/lib/theme/app_colors.g.dart`);
